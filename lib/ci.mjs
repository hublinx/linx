// CI generation (`linx init --ci`) and PR/MR templates. All files here are project-owned: created when
// missing, never overwritten. Existing .gitlab-ci.yml files get an `include:` only when that is safe.
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { detectInstall, detectNodeVersion } from './detect.mjs';

const readOrNull = (p) => (existsSync(p) ? readFileSync(p, 'utf8') : null);
const HEADER = '# Generated by `linx init --ci` — project-owned: edit freely, linx will not overwrite it.';
const GITLAB_JOB = '.gitlab/ci/linx.yml';
const GITHUB_PR_TEMPLATES = [
    '.github/pull_request_template.md',
    '.github/PULL_REQUEST_TEMPLATE.md',
    '.github/PULL_REQUEST_TEMPLATE',
    'docs/pull_request_template.md',
    'pull_request_template.md',
];

function githubSetup(setup, node) {
    if (!setup) return ['      # TODO: set up your toolchain and install dependencies here.'];
    const lines = [];
    if (setup.pm === 'pnpm')
        lines.push('      - uses: pnpm/action-setup@v4', ...(setup.pinned ? [] : ['        with:', '          version: 9']));
    if (setup.pm === 'bun') lines.push('      - uses: oven-sh/setup-bun@v2');
    if (setup.berry) lines.push('      - run: corepack enable');
    lines.push('      - uses: actions/setup-node@v4', '        with:', `          node-version: '${node}'`);
    if (setup.pm !== 'bun') lines.push(`          cache: ${setup.pm}`);
    lines.push(`      - run: ${setup.install}`);
    return lines;
}

export function githubWorkflow(dir, config, version) {
    return [
        HEADER,
        'name: linx',
        'on:',
        '  pull_request:',
        '  push:',
        `    branches: [${config.baseBranch ?? 'main'}]`,
        'jobs:',
        '  verify:',
        '    runs-on: ubuntu-latest',
        '    steps:',
        '      - uses: actions/checkout@v4',
        ...githubSetup(detectInstall(dir), detectNodeVersion(dir)),
        '      - name: Verify gate',
        '        run: node .linx/verify.mjs',
        '      - name: linx-managed files unchanged',
        `        run: npx -y github:hublinx/linx#v${version} check`,
        '',
    ].join('\n');
}

export function gitlabJob(dir, config, version) {
    const setup = detectInstall(dir);
    const install = !setup
        ? ['    # TODO: install your toolchain and dependencies (this image only has Node).']
        : [`    - ${setup.pm === 'pnpm' || setup.berry ? 'corepack enable && ' : ''}${setup.install}`];
    return [
        HEADER,
        'linx-verify:',
        // Full (non-alpine) image: `npx github:...` needs git.
        `  image: node:${detectNodeVersion(dir)}`,
        '  stage: test',
        '  rules:',
        '    - if: $CI_PIPELINE_SOURCE == "merge_request_event"',
        `    - if: $CI_COMMIT_BRANCH == "${config.baseBranch ?? 'main'}"`,
        '  variables:',
        '    NODE_OPTIONS: --max-old-space-size=4096',
        ...(setup ? ['  cache:', '    key:', `      files: [${setup.lockfile}]`, '    paths: [node_modules/]'] : []),
        '  script:',
        ...install,
        '    - node .linx/verify.mjs',
        `    - npx -y github:hublinx/linx#v${version} check`,
        '',
    ].join('\n');
}

/** Actions for the CI files. `manual` = we could not edit safely; `note` says what to add by hand. */
export function ciActions(dir, config, version) {
    if (config.forge === 'github') {
        const rel = '.github/workflows/linx.yml';
        return existsSync(join(dir, rel)) ? [] : [{ rel, action: 'create', content: githubWorkflow(dir, config, version) }];
    }
    if (config.forge !== 'gitlab')
        return [{ rel: '(ci)', action: 'manual', note: 'forge is not github/gitlab — set "forge" in .linx/config.json' }];

    const actions = [];
    if (!existsSync(join(dir, GITLAB_JOB)))
        actions.push({ rel: GITLAB_JOB, action: 'create', content: gitlabJob(dir, config, version) });
    const main = readOrNull(join(dir, '.gitlab-ci.yml'));
    const include = `include:\n  - local: ${GITLAB_JOB}\n`;
    if (main === null) actions.push({ rel: '.gitlab-ci.yml', action: 'create', content: `${include}` });
    else if (main.includes(GITLAB_JOB)) return actions;
    else if (/^include:/m.test(main))
        actions.push({ rel: '.gitlab-ci.yml', action: 'manual', note: `add "- local: ${GITLAB_JOB}" under include:` });
    else if (/^stages:/m.test(main) && !/^stages:[\s\S]*?^\s*-\s*test\b/m.test(main))
        actions.push({ rel: '.gitlab-ci.yml', action: 'manual', note: `add a "test" stage, then include ${GITLAB_JOB}` });
    else actions.push({ rel: '.gitlab-ci.yml', action: 'merge', content: `${main.trimEnd()}\n\n${include}` });
    return actions;
}

export function templateActions(dir, config, content) {
    if (config.forge === 'github') {
        if (GITHUB_PR_TEMPLATES.some((p) => existsSync(join(dir, p)))) return [];
        return [{ rel: '.github/pull_request_template.md', action: 'create', content }];
    }
    if (config.forge === 'gitlab') {
        if (existsSync(join(dir, '.gitlab', 'merge_request_templates'))) return [];
        // GitLab applies a template named "Default" automatically to new MRs.
        return [{ rel: '.gitlab/merge_request_templates/Default.md', action: 'create', content }];
    }
    return [];
}
